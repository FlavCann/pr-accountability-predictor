"""The gold set: loading, fingerprinting, validation, splits and leakage.

Gold files are generated by `evals/build_gold.py` from labelled phrases and are
never edited by hand. Format (evals/gold/*.json):

    {
      "source_url": "...",
      "source_text_hash": "...",     # content_hash of the text the labels index
      "split": "dev",                # examples | dev | test | fresh
      "exhaustive": false,           # every promise in the document labelled?
      "labelled_by": "who",
      "promises": [
        {"start_char": 123, "end_char": 200, "promise_type": "...",
         "hedge_level": "...", "note": "why this is a promise",
         "deadline_raw": "...", "deadline_resolved": null,
         "thread_key": "...", "slices": ["fiscal_deadline"]}
      ],
      "must_not_extract": [
        {"start_char": 50, "end_char": 90, "note": "catering joke"}
      ],
      "masked": [
        {"start_char": 3281, "end_char": 3420, "note": "prompt example"}
      ],
      "labelling_complete": true
    }

`masked` spans are excluded from scoring: nothing inside them is a true or
false positive, and nothing inside them is labelled. They exist so a transcript
that supplies one prompt example can still be held out -- the example passage
is masked, and the rest of the document is scored. `labelling_complete: false`
marks a document whose labels are in progress: its masks count for leakage
checks, but it is not scored.

`deadline_resolved` is three-valued: absent means "not labelled, do not
score"; null means "the correct output is null" (for example a fiscal-year
phrase, which must not be guessed into a calendar date); a date is the date.
"""

from __future__ import annotations

import json
from dataclasses import dataclass, field, fields
from pathlib import Path
from typing import Dict, List, Optional, Sequence, Tuple

from .. import config
from ..domain import content_hash

SPLITS = ("examples", "dev", "test", "fresh")
SCORED_SPLITS = ("dev", "test", "fresh")
"""`examples` transcripts are the only place prompt examples may come from, so
they are never scored. `test` is held out: iterate on `dev`, promote on `test`.
`fresh` holds transcripts published after the executor's training cutoff."""

SPLITS_FILE = "splits.json"
"""Split assignment for every transcript in the corpus, labelled or not, so a
transcript is committed to a split before anyone reads it for examples."""


@dataclass
class GoldPromise:
    start_char: int
    end_char: int
    promise_type: Optional[str] = None
    hedge_level: Optional[str] = None
    note: str = ""
    deadline_raw: Optional[str] = None
    deadline_resolved: Optional[str] = None
    deadline_labelled: bool = False
    """True when the label file carries `deadline_resolved`, even as null."""
    thread_key: Optional[str] = None
    """Promises with the same key are one commitment, restated."""
    revision_of: Optional[str] = None
    """The thread_key this promise revises (a moved deadline). Merging the two
    is a hard failure -- CLAUDE.md invariant 6."""
    claim: Optional[str] = None
    """A clean restatement, used as `normalized_claim` when threading is scored
    in isolation. Falls back to the verbatim span."""
    slices: List[str] = field(default_factory=list)
    ambiguous: bool = False
    """Annotators disagreed. Never a false negative when missed, never a true
    positive when found; reported separately."""

    @property
    def span(self) -> Tuple[int, int]:
        return (self.start_char, self.end_char)


@dataclass
class GoldDoc:
    source_url: str
    promises: List[GoldPromise] = field(default_factory=list)
    must_not_extract: List[GoldPromise] = field(default_factory=list)
    labelled_by: str = "unknown"
    path: Optional[Path] = None
    exhaustive: bool = False
    """True only if EVERY promise in the transcript is labelled. When False, an
    extraction that matches no label is `unjudged`, not a false positive -- it
    may be a real promise nobody labelled. Scoring it as wrong would punish the
    model for recall and make precision meaningless."""
    split: str = "dev"
    source_text_hash: Optional[str] = None
    source_title: Optional[str] = None
    masked: List[GoldPromise] = field(default_factory=list)
    labelling_complete: bool = True
    provenance: str = "human"
    """Who produced the labels. Anything other than "human" means the answer
    key is not independent of the models it grades, and every result says so."""

    @property
    def name(self) -> str:
        return self.path.name if self.path else self.source_url


_GOLD_FIELDS = {f.name for f in fields(GoldPromise)}


def _gold_promise(raw: Dict) -> GoldPromise:
    kw = {k: v for k, v in raw.items() if k in _GOLD_FIELDS}
    kw["deadline_labelled"] = "deadline_resolved" in raw
    kw["slices"] = list(raw.get("slices") or [])
    return GoldPromise(**kw)


def load_gold(
    directory: Optional[Path] = None, splits: Optional[Sequence[str]] = None
) -> List[GoldDoc]:
    """Every gold document, optionally only those in `splits`."""
    directory = Path(directory or config.GOLD_DIR)
    docs = []
    for path in sorted(directory.glob("*.json")):
        raw = json.loads(path.read_text())
        doc = GoldDoc(
            source_url=raw["source_url"],
            labelled_by=raw.get("labelled_by", "unknown"),
            promises=[_gold_promise(p) for p in raw.get("promises", [])],
            must_not_extract=[_gold_promise(p) for p in raw.get("must_not_extract", [])],
            path=path,
            exhaustive=bool(raw.get("exhaustive", False)),
            split=raw.get("split", "dev"),
            source_text_hash=raw.get("source_text_hash"),
            source_title=raw.get("source_title"),
            masked=[_gold_promise(p) for p in raw.get("masked", [])],
            labelling_complete=bool(raw.get("labelling_complete", True)),
            provenance=raw.get("provenance", "human"),
        )
        if splits is None or doc.split in splits:
            docs.append(doc)
    return docs


def load_splits(directory: Optional[Path] = None) -> Dict[str, str]:
    """Video ID -> split, for the whole corpus. Empty if the file is absent."""
    path = Path(directory or config.GOLD_DIR).parent / SPLITS_FILE
    if not path.exists():
        return {}
    raw = json.loads(path.read_text())
    return {vid: split for split, ids in raw.get("splits", {}).items() for vid in ids}


def gold_fingerprint(docs: List[GoldDoc]) -> str:
    """Identifies the exact label set a score was computed against.

    Covers everything that is scored -- spans, types, hedges, deadlines, thread
    keys, ambiguity, splits -- and the hash of the text the offsets index.
    Scores against different fingerprints are not comparable, and the
    fingerprint changes every time unjudged extractions are labelled.
    """
    parts = []
    for d in sorted(docs, key=lambda d: d.source_url):
        parts += [d.source_url, d.split, d.source_text_hash or "?", "X" if d.exhaustive else "-",
                  "R" if d.labelling_complete else "WIP", d.provenance]
        for g in d.promises:
            parts.append(
                "P{}-{}:{}:{}:{}:{}:{}:{}:{}".format(
                    g.start_char, g.end_char, g.promise_type, g.hedge_level,
                    g.deadline_resolved if g.deadline_labelled else "~",
                    g.thread_key, g.revision_of, int(g.ambiguous), ",".join(sorted(g.slices)),
                )
            )
        parts += ["N{}-{}".format(g.start_char, g.end_char) for g in d.must_not_extract]
        parts += ["M{}-{}".format(g.start_char, g.end_char) for g in d.masked]
    return content_hash("|".join(parts))


def validate_gold(store, docs: List[GoldDoc]) -> List[str]:
    """Check every gold span resolves against the stored source.

    A gold set with stale offsets silently reports garbage, so this runs before
    every eval. The text hash catches a re-fetched transcript whose offsets
    still happen to be in range but now point at different words.
    """
    problems = []
    for doc in docs:
        if doc.split not in SPLITS:
            problems.append("{}: unknown split {!r}".format(doc.name, doc.split))
        src = store.source_by_url(doc.source_url)
        if src is None:
            problems.append("{}: source not in store ({})".format(doc.path, doc.source_url))
            continue
        if doc.source_text_hash and src.text_hash != doc.source_text_hash:
            problems.append(
                "{}: source text changed since labelling (labelled {}, store has {}). "
                "Re-run evals/build_gold.py.".format(doc.name, doc.source_text_hash, src.text_hash)
            )
            continue
        for label, items in (
            ("promise", doc.promises), ("negative", doc.must_not_extract), ("mask", doc.masked)
        ):
            for g in items:
                if g.end_char > len(src.text) or g.start_char < 0 or g.end_char <= g.start_char:
                    problems.append(
                        "{}: {} span {}-{} out of range (len {})".format(
                            doc.path, label, g.start_char, g.end_char, len(src.text)
                        )
                    )
                elif not src.text[g.start_char : g.end_char].strip():
                    problems.append(
                        "{}: {} span {}-{} is blank".format(
                            doc.path, label, g.start_char, g.end_char
                        )
                    )
    return problems


def _norm(text: str) -> str:
    return " ".join("".join(c if c.isalnum() else " " for c in text.lower()).split())


def _youtube_url(video_id: str) -> str:
    return "https://www.youtube.com/watch?v={}".format(video_id)


def find_leakage(store, docs: List[GoldDoc], prompt_text: str) -> List[str]:
    """Every way the model could have seen the answers before being tested.

    Three checks:

    1. A worked example in the taxonomy occurs anywhere in a scored gold
       transcript -- even an unlabelled passage.
    2. A labelled gold span occurs in the prompt text, however it got there.
    3. A worked example occurs in a transcript that `splits.json` assigns to a
       scored split but that is not labelled yet. This catches contamination
       before the labels exist, when it is still cheap to fix.

    Documents in the `examples` split are exempt: that is where examples come
    from, and they are never scored. An example that lies entirely inside a
    document's `masked` span is allowed, because that span is never scored.

    `run_eval` refuses to run while this returns anything. It exists because
    extract-v2 shipped with three contaminated examples and nothing caught it.
    """
    from ..taxonomy import EXCLUSIONS, INCLUSIONS

    examples = [ex for _, ex, _ in EXCLUSIONS] + [ex for ex, _, _, _ in INCLUSIONS]
    prompt_norm = _norm(prompt_text)
    problems = []

    def _examples_in(name: str, text: str, masked=()) -> None:
        source_norm = _norm(text)
        masked_norm = [_norm(text[m.start_char : m.end_char]) for m in masked]
        for ex in examples:
            ex_norm = _norm(ex)
            if ex_norm in source_norm and not any(ex_norm in m for m in masked_norm):
                problems.append(
                    "{}: prompt example is taken from this gold transcript: {!r}".format(
                        name, ex[:70]
                    )
                )

    labelled_urls = set()
    for doc in docs:
        labelled_urls.add(doc.source_url)
        if doc.split == "examples":
            continue
        src = store.source_by_url(doc.source_url)
        if src is None:
            continue
        _examples_in(doc.name, src.text, doc.masked)

        for kind, items in (("promise", doc.promises), ("negative", doc.must_not_extract)):
            for g in items:
                span = _norm(src.text[g.start_char : g.end_char])
                if len(span) >= 25 and span in prompt_norm:
                    problems.append(
                        "{}: labelled {} appears in the prompt: {!r}".format(
                            doc.name, kind, span[:70]
                        )
                    )

    gold_dir = docs[0].path.parent if docs and docs[0].path else None
    for video_id, split in sorted(load_splits(gold_dir).items()):
        url = _youtube_url(video_id)
        if split not in SCORED_SPLITS or url in labelled_urls:
            continue
        src = store.source_by_url(url)
        if src is not None:
            _examples_in("{} (split {}, unlabelled)".format(video_id, split), src.text)
    return problems
